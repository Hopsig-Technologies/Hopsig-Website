"""Every link on every reference page must exist in the site's content with the same label and destination.

    node scripts/content_corpus.mjs            # produces audit/content-corpus.json
    python scripts/check_links.py

Page-body links are compared against that page's module in web/content/pages (buttons, CTAs, <a href> inside
rich strings); header and footer destinations against web/content/navigation.ts. Links that render from
collection data (case rows, service sheets, note rows) are generated by the templates, not stored, and are skipped.
"""
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from extract_pages import ROOT, SITE, ROUTES, PAGES, Tree, inline_html, route_of  # noqa: E402

CORPUS = os.path.join(ROOT, 'audit', 'content-corpus.json')
GENERATED = {'read the case note', 'ask about this', 'details', 'read the note', 'read', 'read the offer', 'read the service'}


def norm(label):
    return re.sub(r'\s+', ' ', re.sub(r'<[^>]+>', '', label)).replace('→', '').strip().casefold()


def page_links(ref):
    t = Tree()
    t.feed(open(os.path.join(SITE, ref), encoding='utf-8').read())
    body, chrome = set(), set()

    def walk(n, area):
        if n.tag in ('script', 'style'):
            return
        cls = n.attrs.get('class', '').split()
        if n.tag == 'footer' or 'hdr' in cls:
            area = 'chrome'
        if n.tag == 'a':
            href = n.attrs.get('href', '')
            label = norm(inline_html(n, ref))
            if label and href and href != '#':
                r = route_of(href, ref)
                if r.startswith('#'):
                    r = ROUTES[ref] + r  # in-page anchor
                (chrome if area == 'chrome' else body).add((label, r))
            return
        for c in n.children:
            if not isinstance(c, str):
                walk(c, area)

    walk(t.root, 'body')
    return body, chrome


def main():
    if not os.path.exists(CORPUS):
        sys.exit('audit/content-corpus.json is missing: run `node scripts/content_corpus.mjs` first')
    corpus = json.load(open(CORPUS, encoding='utf-8'))
    nav = {l['href'] for l in corpus['web/content/navigation.ts']['links']}
    failures = 0
    for name, ref in PAGES.items():
        route = ROUTES[ref]
        body, chrome = page_links(ref)
        have = {(norm(l['label']), l['href']) for l in corpus[f'web/content/pages/{name}.ts']['links']}
        # A label with {tokens} ("All {count} case notes") is filled at render time: match it as a pattern.
        patterns = [(re.compile('^' + re.sub(r'\\{\w+\\}', '.+', re.escape(l)) + '$'), h) for l, h in have if '{' in l]
        missing = sorted(l for l in body - have
                         if not any(rx.match(l[0]) and h == l[1] for rx, h in patterns)
                         and l[0] not in GENERATED
                         and not re.match(r'^\d{2}', l[0])  # numbered rows render from collections
                         and not l[1].startswith(('/work/', '/notes/', '/services/', '/industries/')))
        # Header/footer: menu labels are composed (number + label + description), so compare destinations only.
        missing_nav = sorted({r for l, r in chrome if l != 'hopsigtechnologies'} - nav)  # wordmark -> / is code
        if missing or missing_nav:
            failures += len(missing) + len(missing_nav)
            print(f'{route} ({name})')
            for l in missing:
                print('   body:', l)
            for l in missing_nav:
                print('   header/footer:', l)
    print(f'\n{failures} link(s) in the reference with no matching label + destination in the content')
    return 1 if failures else 0


if __name__ == '__main__':
    sys.stdout.reconfigure(encoding='utf-8')
    sys.exit(main())
